const fs=require('fs'),assert=require('assert'),vm=require('vm');
const html=fs.readFileSync('index.html','utf8');
assert(html.includes('filter:brightness(0) invert(1)!important;opacity:1!important'),'Calendário deve ficar branco');
const script=html.match(/<script\s*>([\s\S]*?)<\/script>/);assert(script,'Script principal ausente');
const js=script[1];
new vm.Script(js,{filename:'index.html'});
const start=js.indexOf('function renderStockChart(');
const end=js.indexOf('\n// Faturas pendentes',start);
assert(start>=0&&end>start);
const render=js.slice(start,end);
const S={};
const context=vm.createContext({Date,Map,Math,Number,String,Array,Set,console,MESES:['Jan','Fev','Mar','Abr','Mai','Jun','Jul','Ago','Set','Out','Nov','Dez'],ensureInvestHistory:i=>i.historico,fmt:v=>'R$ '+Number(v).toFixed(2),escHtml:s=>String(s),today:()=> '2026-10-17',calcInvestMonthResult:()=>({rendimento:0,pct:0}),fmtInvestPct:v=>v.toFixed(2)+'%',renderStockChart:null});
vm.runInContext(render,context);
const invest={id:1,historico:[{data:'2026-09-30',tipo:'aporte',valor:1000,saldo:1000},{data:'2026-10-10',tipo:'resgate',valor:200,saldo:800},{data:'2026-10-10',tipo:'resgate',valor:100,saldo:700},{data:'2026-10-11',tipo:'atualizacao',valor:705,saldo:705}]};
const month=context.renderStockChart(invest,'2026-10','mes');
assert(month.includes('Resgate de R$ 300.00 em 10/10'),'Marcador soma resgates do mesmo dia');
assert(month.includes('10/10 · R$ 300.00'),'Legenda do resgate');
assert.strictEqual((month.match(/class="inv-evolution-resgate-marker"/g)||[]).length,1,'Um marcador por dia');
assert(month.includes('L')&&month.includes('class="inv-evolution-svg"'),'Curva original preservada');
const year=context.renderStockChart(invest,'2026-10','ano');
assert(year.includes('Out/26 · R$ 300.00'),'Marcador de resgate agregado por mês no gráfico anual');
const noWithdraw=context.renderStockChart({id:2,historico:[{data:'2026-10-01',tipo:'aporte',valor:300,saldo:300}]},'2026-10','mes');
assert(!noWithdraw.includes('inv-evolution-resgate-events'),'Sem indicação indevida quando não há resgate');
console.log('PASS: calendário branco, marcadores de resgate mensal/anual, agrupamento e curva preservada');
